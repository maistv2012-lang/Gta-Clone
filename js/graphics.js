import * as THREE from 'three';
import { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
import { EffectComposer } from 'three/addons/postprocessing/EffectComposer.js';
import { RenderPass } from 'three/addons/postprocessing/RenderPass.js';
import { UnrealBloomPass } from 'three/addons/postprocessing/UnrealBloomPass.js';
import { OutputPass } from 'three/addons/postprocessing/OutputPass.js';

// No WebGL context is allocated until PLAY. The HTML menu must not depend on
// GPU initialization, and optional HDR targets must not make the world black.
export function createGraphics(scene, camera, pixelRatio) {
  const renderer = new THREE.WebGLRenderer({ antialias: true });
  renderer.domElement.id = 'game';
  renderer.setPixelRatio(pixelRatio);
  renderer.setSize(Math.max(1, innerWidth), Math.max(1, innerHeight));
  renderer.shadowMap.enabled = true;
  renderer.shadowMap.type = THREE.PCFSoftShadowMap;
  renderer.toneMapping = THREE.ACESFilmicToneMapping;
  renderer.toneMappingExposure = 1.1;
  const gl = renderer.getContext();
  let hdr = renderer.extensions.has('EXT_color_buffer_float') || renderer.extensions.has('EXT_color_buffer_half_float');
  if (hdr) {
    const probe = new THREE.WebGLRenderTarget(4, 4, { type: THREE.HalfFloatType });
    try {
      renderer.setRenderTarget(probe);
      hdr = gl.checkFramebufferStatus(gl.FRAMEBUFFER) === gl.FRAMEBUFFER_COMPLETE && gl.getError() === gl.NO_ERROR;
    } finally { renderer.setRenderTarget(null); probe.dispose(); }
    // Discard only errors generated by the failed capability probe.
    if (!hdr) for (let i = 0; i < 8 && gl.getError() !== gl.NO_ERROR; i++) {}
  }
  let composer = null, bloom = null, environment = null;
  if (hdr) {
    const room = new RoomEnvironment(), pmrem = new THREE.PMREMGenerator(renderer);
    try { environment = pmrem.fromScene(room, 0.04); scene.environment = environment.texture; }
    finally { pmrem.dispose(); room.dispose(); }
    composer = new EffectComposer(renderer);
    composer.addPass(new RenderPass(scene, camera));
    bloom = new UnrealBloomPass(new THREE.Vector2(innerWidth, innerHeight), 0.28, 0.55, 0.82);
    composer.addPass(bloom);
    composer.addPass(new OutputPass());
  } else {
    console.warn('Christchurch: float render targets unavailable; using direct WebGL rendering.');
  }
  let frames = 0;
  const graphics = {
    renderer, composer, bloom,
    render(lowGfx) {
      if (gl.isContextLost()) throw new Error('O contexto WebGL foi perdido antes de renderizar o cenário.');
      if (hdr && !lowGfx) composer.render();
      else renderer.render(scene, camera);
      frames++;
    },
    verifyFirstFrame() {
      const error = gl.getError();
      if (error !== gl.NO_ERROR || gl.isContextLost()) {
        throw new Error(`WebGL não conseguiu desenhar o cenário (erro ${error}). O menu foi preservado.`);
      }
      if (!frames || !renderer.info.render.calls) throw new Error('O cenário 3D ainda não produziu um frame.');
      // A renderer can report draw calls without producing visible pixels.
      // Read a small grid once, before the menu is hidden (not every frame).
      const pixel = new Uint8Array(4);
      let visible = false, first = null, variation = 0;
      for (const u of [.2, .5, .8]) for (const v of [.25, .5, .75]) {
        gl.readPixels(Math.floor(gl.drawingBufferWidth * u), Math.floor(gl.drawingBufferHeight * v), 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixel);
        if (pixel[0] + pixel[1] + pixel[2] > 12) visible = true;
        if (!first) first = [...pixel];
        variation = Math.max(variation, Math.abs(pixel[0] - first[0]) + Math.abs(pixel[1] - first[1]) + Math.abs(pixel[2] - first[2]));
      }
      if (!visible || variation < 8 || gl.getError() !== gl.NO_ERROR) throw new Error('O WebGL produziu um frame preto ou sem cenário visível. O menu foi mantido; tente novamente ou verifique o suporte gráfico da Prévia.');
    },
    diagnostics: () => ({ initialized: true, frames, hdr, contextLost: gl.isContextLost(), width: gl.drawingBufferWidth, height: gl.drawingBufferHeight }),
  };
  return graphics;
}
